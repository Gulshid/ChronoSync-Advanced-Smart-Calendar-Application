  static String lang = 'en';

  static String t(String key, [Map<String, Object> args = const {}]) {
    final table = lang == 'ur' ? _ur : _en;
    var text = table[key] ?? _en[key] ?? key;
    args.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
    return text;
  }

  /// "45 minutes", "1 h 30 min", "2 days" and so on.
  static String durationText(Duration d) {
    final totalMin = d.inMinutes;
    if (totalMin >= 1440 && totalMin % 1440 == 0) {
      final days = totalMin ~/ 1440;
      return days == 1 ? t('dur_day_one') : t('dur_days', {'n': days});
    }
    final h = totalMin ~/ 60;
    final m = totalMin % 60;
    if (h > 0 && m > 0) return t('dur_hm', {'h': h, 'm': m});
    if (h > 0) return t('dur_hour', {'n': h});
    return t('dur_min', {'n': m});
  }

  /// Label for a reminder lead time, e.g. "10 min before" or "At time of event".
  static String leadLabel(int minutes) =>
      minutes == 0 ? t('at_time') : t('before', {'d': durationText(Duration(minutes: minutes))});

